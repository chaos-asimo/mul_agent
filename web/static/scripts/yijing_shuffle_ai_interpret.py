# 模拟本地提供的“开始摇卦”功能
def local_start_shaking():
    """
    模拟本地“开始摇卦”API或功能。
    返回一个包含6爻结果的字典或列表。
    这里假设返回的是一个包含6个元素的列表，每个元素代表一爻：
    - 0: 老阴 (变爻)
    - 1: 少阳 (不变)
    - 2: 老阳 (变爻)
    - 3: 少阴 (不变)
    或者更常见的表示法：
    - 6: 老阴 (变爻)
    - 7: 少阳 (不变)
    - 8: 少阴 (不变)
    - 9: 老阳 (变爻)
    
    为了简化，我们使用 6, 7, 8, 9 表示四象。
    """
    yao_results = []
    for _ in range(6):
        # 模拟掷铜钱：3枚铜钱，正面(3)或反面(2)
        # 总和：6(老阴), 7(少阳), 8(少阴), 9(老阳)
        coin1 = random.choice([2, 3])
        coin2 = random.choice([2, 3])
        coin3 = random.choice([2, 3])
        total = coin1 + coin2 + coin3
        yao_results.append(total)
    return yao_results

